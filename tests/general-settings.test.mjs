import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
const persistent = new Map(), session = new Map();
const storage = map => ({ getItem: key => map.get(key) ?? null, setItem: (key, value) => map.set(key, String(value)), removeItem: key => map.delete(key) });
const context = { console, Date, Intl, localStorage: storage(persistent), sessionStorage: storage(session), dispatchEvent() {}, addEventListener() {}, CustomEvent: class {}, location: { hash: '' } };
context.window = context;
vm.createContext(context);
for (const name of ['auth.js', 'permissions.js', 'data.js', 'billing.js', 'general-settings.js']) vm.runInContext(readFileSync(name, 'utf8'), context, { filename: name });
const { RH, RHP, RHD, RHGeneralSettings: api } = context;
// Disposable fixtures only. No browser profile or production localStorage is used.
const admin = { id: 'admin', name: 'Quản lý', role: 'manager', status: 'active', accountTypeId: RHP.ADMIN_TYPE_ID };
const staff = { id: 'staff', name: 'Nhân viên', role: 'manager', status: 'active', accountTypeId: 'test-settings', buildingIds: ['b1'] };
persistent.set('residenthub_users', JSON.stringify([admin, staff, { id: 'resident', name: 'Cư dân A', role: 'resident', status: 'active', apartmentId: 'a1' }, { id: 'other', name: 'Cư dân B', role: 'resident', status: 'active', apartmentId: 'a2' }, { id: 'locked', name: 'Đã khóa', role: 'resident', status: 'locked', apartmentId: 'a1' }].map(user => ({ ...user, email: user.id + '@example.test', password: 'test-password' }))));
const types = JSON.parse(persistent.get('residenthub_account_types'));
types.push({ id: 'test-settings', name: 'Xem cài đặt', portal: 'manager', permissions: ['settings.view', 'buildings.view'] });
persistent.set('residenthub_account_types', JSON.stringify(types));
RH.login(admin, false);
RHD.create('buildings', { id: 'b1', name: 'Tòa A', config: { bankName: 'ACB', bankAccountNumber: '001234', bankAccountHolder: 'A' } });
RHD.create('buildings', { id: 'b2', name: 'Tòa B' });
RHD.create('apartments', { id: 'a1', name: '101', buildingId: 'b1' });
RHD.create('apartments', { id: 'a2', name: '102', buildingId: 'b2' });
const invoice = { id: 'i1', code: 'HD-1', apartmentId: 'a1', buildingId: 'b1', status: 'sent', issuedAt: 123, dueDate: '2026-10-20', total: 100000 };
RHD.create('invoices', invoice);
RHD.create('invoices', { ...invoice, id: 'draft', status: 'draft' });
RHD.create('invoices', { ...invoice, id: 'paid', status: 'paid' });
RHD.create('invoices', { ...invoice, id: 'legacy', issuedAt: null });
RHD.create('contracts', { id: 'c1', code: 'HĐ-1', apartmentId: 'a1', buildingId: 'b1', status: 'active', endDate: '2026-10-20' });
const values = { notifyInvoice: true, notifyContract: true, notifySupportStatus: false, invoiceReminderDays: '1,0,1', contractReminderDays: '1', templates: { invoice: '{Ten_Cu_Dan} {Ma_Doi_Tuong} {So_Tien}', reminder: '{Ma_Doi_Tuong} {So_Ngay}', contract: '{Toa_Nha} {Ngay_Han}' } };
const saved = api.saveNotifications(values);
assert.equal(saved.invoiceReminderDays, '1,0');
assert.equal(RHD.getSettings().notifySupportStatus, false);
const originalInvoices = JSON.stringify(RHD.list('invoices'));
const originalBuildings = JSON.stringify(RHD.list('buildings'));
assert.equal(api.synchronize(new Date('2026-10-19T05:00:00Z')), 3);
assert.equal(api.synchronize(new Date('2026-10-19T05:00:00Z')), 0);
const inbox = RH.getNotificationsForUser('resident');
assert.equal(inbox.length, 3);
assert.equal(inbox.every(n => n.isRead === false && n.refId && ['invoices', 'contracts'].includes(n.actionUrl)), true);
assert.ok(inbox.find(n => n.body.includes('Cư dân A HD-1 100.000')));
assert.equal(RH.getNotificationsForUser('other').length, 0);
assert.equal(RH.getNotificationsForUser('locked').length, 0);
assert.equal(JSON.stringify(RHD.list('invoices')), originalInvoices);
assert.equal(JSON.stringify(RHD.list('buildings')), originalBuildings);
RH.updateNotificationForUser('resident', inbox[0].id, { isRead: true });
assert.equal(RH.getNotificationsForUser('resident')[0].isRead, true);
assert.throws(() => api.saveNotifications({ ...values, invoiceReminderDays: '-1' }), /Ngày nhắc/);
assert.throws(() => api.saveNotifications({ ...values, templates: { ...values.templates, invoice: '{password}' } }), /trường dữ liệu/);
RHD.update('invoices', 'i1', { status: 'paid', password: 'secret', token: 'secret' });
let logs = api.logs();
assert.equal(logs.at(-1).actorId, admin.id);
assert.equal(logs.at(-1).before.status, 'sent');
assert.equal(logs.at(-1).after.status, 'paid');
assert.equal(JSON.stringify(logs).includes('secret'), false);
assert.equal(api.filterLogs(logs, { user: 'quản lý', module: 'invoices', action: 'update' }).length, 1);
assert.equal(api.filterLogs([{ at: '2026-10-18T18:00:00Z', actorName: 'A' }], { from: '2026-10-19', to: '2026-10-19' }).length, 1);
RH.login(staff, false);
assert.throws(() => api.saveNotifications(values), /không có quyền/);
assert.throws(() => api.synchronize(), /không có quyền/);
assert.ok(api.logs().every(r => r.buildingId === 'b1'));
RH.login(admin, false);
RHD.setMode('demo');
assert.throws(() => api.synchronize(), /Demo/);
assert.equal(api.logs().length, 0);
RHD.setMode('live');
persistent.set('residenthub_live_activity_v1', '{broken');
RHD.update('invoices', 'i1', { status: 'paid' });
assert.equal(persistent.get('residenthub_live_activity_v1'), '{broken');
assert.throws(() => api.logs());
console.log('Passed: actual RH/RHD/RHP integration; scoped recipients; drafts/paid/locked/demo excluded; idempotency; read state; invoice/bank immutability; template validation; audit allowlist and filters; corrupt log preserved.');
