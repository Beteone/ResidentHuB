import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
const storage = new Map();
const context = vm.createContext({ console, Date, Math, Set, JSON, Number, String, Array, Object,
    localStorage:{getItem:k=>storage.get(k) ?? null,setItem:(k,v)=>storage.set(k,v)},
    sessionStorage:{getItem:()=>null,setItem:()=>{}}, location:{hash:'',href:''},
    CustomEvent:class {}, dispatchEvent:()=>{}, addEventListener:()=>{} });
context.window=context;
for (const file of ['auth.js','permissions.js','templates.js','data.js','contract-documents.js','money-input.js']) vm.runInContext(readFileSync(file,'utf8'),context,{filename:file});
const {RHD:d,RHT:t,RHDocuments:docs,RHMoney:money,RH:auth}=context;
let granted=new Set(['contracts.create','contracts.update','templates.create','templates.update']);
context.RHP={...context.RHP,can:k=>granted.has(k),inScope:id=>id==='b',scopeList:(_,rows)=>rows};
t.seed();
assert.equal(money.format('1000000'),'1.000.000'); assert.equal(money.parse('1.000.000'),1000000);
assert.equal(money.parse('1.000.000,25'),1000000.25); assert.equal(money.format(''),'');
d.create('buildings',{id:'b',name:'Building',shortName:'B',managerId:'manager',services:[{id:'svc',name:'Internet',unitPrice:100000,calcMethod:'fixed',taxRate:0}]});
d.create('apartments',{id:'a',name:'101',buildingId:'b',maxGuests:2,rentPrice:1000000,depositPrice:1000000});
for(const id of ['p1','p2','p3']) d.create('customers',{id,fullName:id,phone:id==='p1'?'0901234567':'',email:id+'@example.test'});
d.create('assets',{id:'asset',apartmentId:'a',name:'Bed',quantity:2,value:300000});
d.create('contracts',{id:'draft-before-signing',buildingId:'b',apartmentId:'a',customerId:'p1',status:'draft',startDate:'2026-10-01',endDate:'2027-09-30'});
const original=t.getDefault('CONTRACT'), before=JSON.stringify(original);
const originalIds=t.list().map(t=>t.id).sort();
assert.equal(t.groupOf(t.list().find(t=>t.code==='invoice_deposit')),'deposit');
assert.equal(t.groupOf(t.list().find(t=>t.code==='invoice_room_transfer')),'handover');
assert.equal(t.groupOf(t.list().find(t=>t.code==='invoice_liquidation_standard')),'lease');
assert.equal(t.groupOf(t.list().find(t=>t.code==='invoice_monthly')),'vouchers');
assert.deepEqual(t.list().map(t=>t.id).sort(),originalIds,'Classifying never writes or duplicates records');
assert.equal(t.update(original.id,{name:'Overwrite'}).ok,false);
const c1=t.clone(original.id).item,c2=t.clone(original.id).item;
assert.notEqual(c1.id,c2.id);
t.update(c1.id,{name:'Custom',html_template:'<h1>{{contract_code}}</h1>{{tenants_table}}{{assets_table}}{{services_table}}{{initial_costs_table}}'});
assert.equal(JSON.stringify(t.get(original.id)),before);
assert.equal(t.get(c1.id).version,2); assert.equal(t.get(c1.id).history.length,1);
granted.delete('templates.update');
const createdOnly=t.clone(original.id,false,{name:'Create permission only',html_template:'<p>{{tenant_name}}</p>'});
assert.equal(createdOnly.ok,true,'Creating a copy does not require permission to update existing templates');
granted.add('templates.update');
assert.equal(t.setDefault(c1.id,'b').ok,true); assert.equal(t.getDefault('CONTRACT','b').id,c1.id);
const contract={buildingId:'b',apartmentId:'a',customerId:'p1',customerIds:['p1','p2'],code:'C1',startDate:'2026-10-01',endDate:'2027-09-30',signDate:'2026-10-01',rentPrice:1000000,depositPrice:1000000,initialServiceAmount:100000,additionalAmount:0,serviceIds:['svc'],contractTemplateId:c1.id,status:'active',handoverAssets:[{assetId:'asset',name:'Bed',quantity:1,value:300000,condition:'Good'}]};
assert.match(docs.validate({...contract,customerIds:['p1','p2','p3']}),/sức chứa/);
assert.match(docs.validate({...contract,customerIds:['p1','p1']}),/trùng/);
assert.equal(d.create('contracts',{...contract,handoverAssets:[{assetId:'asset',quantity:3}]}).ok,false);
const saved=d.create('contracts',contract); assert.equal(saved.ok,true,saved.error);
assert.equal(saved.item.documentSnapshot.missing.length,0);
assert.ok(saved.item.documentSnapshot.html.includes('p2')); assert.ok(saved.item.documentSnapshot.html.includes('Bed')); assert.ok(saved.item.documentSnapshot.html.includes('Internet'));
const snapshot=JSON.stringify(saved.item.documentSnapshot);
t.update(c1.id,{html_template:'Changed template'});
d.update('customers','p1',{fullName:'Changed name'});
d.update('buildings','b',{services:[]});
assert.equal(JSON.stringify(docs.documentFor(d.get('contracts',saved.item.id))),snapshot);
const missingTemplate=t.create({name:'Incomplete template',type:'CONTRACT',groupId:'other',html_template:'<p>{{company_name}}</p>'}).item;
const signing=docs.prepare({...saved.item,documentSnapshot:null,contractTemplateId:missingTemplate.id},null);
assert.equal(signing.ok,false,'Draft export changes never bypass required signing data');
assert.ok(signing.error.includes('Bên cho thuê'));
const signedHtml=d.get('contracts',saved.item.id).documentSnapshot.html;
assert.equal(t.moveGroup(c1.id,'handover').ok,true);
assert.equal(d.get('contracts',saved.item.id).documentSnapshot.html,signedHtml,'Moving groups never changes signed snapshots');
assert.equal(d.update('contracts',saved.item.id,{note:'Update note'}).ok,true);
assert.equal(JSON.stringify(d.get('contracts',saved.item.id).documentSnapshot),snapshot);
assert.equal(d.create('contracts',{...contract,code:'C2'}).ok,false,'Reject overlapping leases');
assert.deepEqual([...docs.render('{{unknown}}',{}).missing],['unknown']);
assert.ok(docs.missingMessage(['bank_account_number']).includes('Số tài khoản'));
assert.ok(!docs.missingMessage(['bank_account_number']).includes('bank_account_number'));
assert.equal(docs.data({...contract,lessorName:'Owner',lessorRepresentative:'Authorized signer'}).manager_name,'Authorized signer');
const account={role:'resident',accountTypeId:'at-resident',name:'p1',phone:'0901234567',email:'p1@example.test',residentId:'p1',apartmentId:'a',password:'password',allBuildings:false};
assert.equal(auth.createUser(account).ok,false,'No create permission');
granted.add('users.createResident');
const user=auth.createUser(account); assert.equal(user.ok,true,user.error);
assert.equal(user.user.residentId,'p1'); assert.equal(user.user.apartmentId,'a');
assert.equal(auth.createUser({...account,email:'other@example.test'}).ok,false,'Duplicate resident');
assert.equal(auth.createUser({...account,residentId:'p2',email:'p2@example.test',apartmentId:'outside'}).ok,false,'Scope enforcement');
const request=auth.submitAccountRequest({fullName:'Self registrant',phone:'0909876543',email:'self@example.test',password:'password',buildingId:'b',apartmentId:'a'});
assert.equal(request.ok,true,request.error); assert.equal(request.item.status,'pending');
assert.equal(auth.getUsers().some(u=>u.email==='self@example.test'),false,'Self registration never activates a login');
console.log('Passed: permissions, duplicate accounts, money round trip, capacity, duplicate tenants, overlapping leases, handover quantities, immutable system templates, multiple copies, versions, building defaults, missing variables, signed snapshots.');
